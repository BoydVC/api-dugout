// Screenshots of the offline snapshot (file://) at desktop size — hero + lineup.
import { launch, sleep } from "./cdp.mjs";
import { resolve } from "node:path";
import { writeFileSync } from "node:fs";
const url = "file://" + resolve("dist/api-dugout.html");
const b = await launch(9475);
const out = (n) => "screenshots/" + n + ".png";
const setup = async (w, h) => {
  await b.viewport(w, h, false, 1);
  await b.goto(url, 900);
  await b.ev("localStorage.clear()");
  await b.goto(url, 1000);
};
await setup(1440, 900);
await b.ev(`AD.loadPreset("steal2")`);
await sleep(300);
await b.ev(`document.querySelectorAll('#frameChips button')[1].click()`);
await sleep(2200);
await b.shot(out("00-best-home"));
await b.shot(out("desktop-steal-frame2"));
await b.ev(`AD.loadPreset("first3rd")`);
await b.ev(`document.querySelectorAll('#frameChips button')[2].click()`);
await sleep(2200);
await b.shot(out("desktop-first3rd"));
await b.ev(`AD.loadPreset("rundown")`);
await b.ev(`document.querySelectorAll('#frameChips button')[1].click()`);
await sleep(2200);
await b.shot(out("desktop-rundown"));
await b.ev(`AD.setScreen("lineup")`);
await sleep(800);
await b.shot(out("desktop-lineup"));
await b.ev(`AD.setScreen("scorebook")`);
await sleep(800);
await b.shot(out("desktop-scorebook"));
await setup(390, 844);
await b.ev(`AD.loadPreset("bunt")`);
await sleep(2000);
await b.shot(out("phone-390-bunt"));
console.log(JSON.stringify({ errors: b.errors }));
await b.close();
